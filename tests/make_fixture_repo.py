"""Build a synthetic FACETS repository for tests.

Everything here is fake: sample ids are obviously synthetic (P-0000001...), the
manifests carry a deliberately WRONG absolute ``path`` column (``/nonexistent/...``)
so tests prove that fit directories are resolved from the discovered sample
directory, and file contents are the minimum the parsers need. Layout mirrors
the real repository:

    <root>/<id[0:7]>/<tumor>_<normal>/                     standard sample
        facets_review.manifest, facets_qc.txt, <fit>/..., *.maf
    <root>/<id[0:7]>/<tumor>_<normal>/{clinical,research}/  2n pair (no root manifest)
        each class dir is a full standard-shaped sample dir; ultra fits nest as
        research/<fit>/ultra/ and hold ONLY _hisens.* files (as on disk).

Nothing is written outside ``root``. Call ``build(root)``; it returns a dict of
ids and paths the tests use for expectations.
"""

import os

MANIFEST_HEADER = ("sample\tpath\treview_status\tfit_name\treview_notes\treviewed_by\t"
                   "date_reviewed\tfacets_qc\tuse_only_purity_run\tuse_edited_cncf\t"
                   "reviewer_set_purity\tfacets_qc_version\tfacets_suite_version\n")
MANIFEST_COMMENT = "# generated by facets-preview app. DO NOT EDIT.\n"

CNCF_HEADER = ("ID\tchrom\tloc.start\tloc.end\tseg\tnum.mark\tnhet\tcnlr.median\tmafR\tsegclust\t"
               "cnlr.median.clust\tmafR.clust\tcf\ttcn\tlcn\tcf.em\ttcn.em\tlcn.em\n")
SEG_HEADER = "ID\tchrom\tloc.start\tloc.end\tnum.mark\tseg.mean\n"
QC_HEADER = ("sample\tcval\tdipLogR_flag\tn_alternative_dipLogR\twgd\tfga\tn_dip_bal_segs\tfrac_dip_bal_segs\t"
             "n_loh\tfrac_loh\tn_segs\n")
GENE_HEADER = ("sample\tgene\tchrom\tgene_start\tgene_end\ttsg\tseg\tmedian_cnlr_seg\tsegclust\tseg_start\tseg_end\t"
               "cf.em\ttcn.em\tlcn.em\tcf\ttcn\tlcn\tseg_length\tmcn\tgenes_on_seg\tgene_snps\tgene_het_snps\t"
               "spans_segs\tcn_state\tfilter\n")
FACETS_QC_HEADER = ("tumor_sample_id\tpath\tfit_name\tpurity\tploidy\tdipLogR\twgd\tfga\tfrac_loh\tis_best_fit\t"
                    "facets_suite_version\tfacets_qc_version\tfacets_qc\n")
MAF_HEADER = "Hugo_Symbol\tChromosome\tStart_Position\tTumor_Sample_Barcode\tccf_expected_copies\n"

# (chrom, start, end, num.mark, nhet, cnlr.median, mafR, cf, tcn, lcn)  -- tcn/lcn are the .em values too
DEFAULT_SEGMENTS = [
    (1, 10000, 120000000, 900, 300, 0.01, 0.02, 0.6, 2, 1),
    (1, 125100000, 249000000, 800, 250, -0.45, 0.30, 0.6, 1, 0),
    (3, 10000, 90000000, 700, 200, 0.02, 0.01, 0.6, 2, 1),
    (3, 91100000, 198000000, 600, 150, 0.40, 0.10, 0.6, 3, 1),
    (9, 10000, 48000000, 500, 100, -1.50, 0.00, 0.6, 0, 0),
    (17, 10000, 23000000, 400, 90, -0.40, 0.25, 0.6, 1, 0),
    (17, 24100000, 81000000, 400, 90, 0.00, 0.01, 0.6, 2, "NA"),
]

DEFAULT_GENES = [
    ("TP53", 17, 7565097, 7590856, "TRUE", 6, -0.40, 1, 10000, 23000000, 1, 0, "HETLOSS"),
    ("CDKN2A", 9, 21967751, 21995300, "TRUE", 5, -1.50, 2, 10000, 48000000, 0, 0, "HOMDEL"),
    ("PIK3CA", 3, 178866311, 178952497, "FALSE", 4, 0.40, 3, 91100000, 198000000, 3, 1, "GAIN"),
    ("EGFR", 7, 55086714, 55324313, "FALSE", 7, 0.00, 4, 10000, 159000000, 2, 1, "DIPLOID"),
]


def _w(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as fh:
        fh.write(text)


def write_out(path, pair, mode, purity=0.62, ploidy=2.1, diplogr=-0.12, purity_cval=100, cval=50):
    """Minimal facets-suite legacy .out file."""
    lines = [
        "# INPUT PARAMETERS GIVEN",
        "# TAG = " + pair,
        "# Facets version = 0.6.2",
        "# Input = countsMerged____" + pair + ".dat.gz",
        "# Seed = 100",
        "# snp.nbhd = 250",
        "# ndepth = 35",
        "# purity_cval = %d" % purity_cval,
        "# unmatched = FALSE",
        "# cval = %d" % cval,
        "# min.nhet = 15",
        "# genome = hg19",
        "# tumor_id = " + pair.split("_")[0],
        "# LOADED MODULE INFO",
        "# Facets version = 0.6.2",
        "# FACETS OUTPUT",
        "# Purity = %s" % purity,
        "# Ploidy = %s" % ploidy,
        "# dipLogR = %s" % diplogr,
        "# dipt = 2",
        "# loglik = -1234.5",
        "# output flags",
        "# mafR not sufficiently small",
        "",
    ]
    _w(path, "\n".join(lines))


def write_fit(fit_dir, pair, modes=("purity", "hisens"), with_qc_gene=True, with_rdata=True,
              purity=0.62, ploidy=2.1, diplogr=-0.12, wgd=False, fga=0.21, frac_loh=0.13,
              segments=DEFAULT_SEGMENTS, genes=DEFAULT_GENES):
    """Write one fit directory. Ultra fits on disk are hisens-only with no qc/gene files:
    call with modes=("hisens",), with_qc_gene=False."""
    os.makedirs(fit_dir, exist_ok=True)
    for mode in modes:
        write_out(os.path.join(fit_dir, "%s_%s.out" % (pair, mode)), pair, mode,
                  purity=purity, ploidy=ploidy, diplogr=diplogr)
        cncf = [CNCF_HEADER]
        adj = [SEG_HEADER]
        unadj = [SEG_HEADER]
        for i, (chrom, s, e, nm, nhet, cnlr, mafr, cf, tcn, lcn) in enumerate(segments, start=1):
            cncf.append("\t".join(str(x) for x in [pair, chrom, s, e, i, nm, nhet, cnlr, mafr, i, cnlr, mafr,
                                                    cf, tcn, lcn, cf, tcn, lcn]) + "\n")
            adj.append("\t".join(str(x) for x in [pair, chrom, s, e, nm, cnlr - diplogr]) + "\n")
            unadj.append("\t".join(str(x) for x in [pair, chrom, s, e, nm, cnlr]) + "\n")
        _w(os.path.join(fit_dir, "%s_%s.cncf.txt" % (pair, mode)), "".join(cncf))
        _w(os.path.join(fit_dir, "%s_%s_diplogR.adjusted.seg" % (pair, mode)), "".join(adj))
        _w(os.path.join(fit_dir, "%s_%s_diplogR.unadjusted.seg" % (pair, mode)), "".join(unadj))
        if with_rdata:
            _w(os.path.join(fit_dir, "%s_%s.Rdata" % (pair, mode)), "RDX2\n")
    if with_qc_gene:
        qc = [QC_HEADER]
        for cval in (100, 50):
            qc.append("\t".join(str(x) for x in [pair, cval, "FALSE", 1, str(wgd).upper(), fga, 10, 0.5, 3,
                                                  frac_loh, len(segments)]) + "\n")
        _w(os.path.join(fit_dir, pair + ".qc.txt"), "".join(qc))
        gl = [GENE_HEADER]
        for (gene, chrom, gs, ge, tsg, seg, cnlr, segclust, ss, se, tcn, lcn, state) in genes:
            gl.append("\t".join(str(x) for x in [pair, gene, chrom, gs, ge, tsg, seg, cnlr, segclust, ss, se,
                                                  0.6, tcn, lcn, 0.6, tcn, lcn, se - ss, tcn - (lcn if lcn != "NA" else 0),
                                                  3, 40, 12, "FALSE", state, "PASS"]) + "\n")
        _w(os.path.join(fit_dir, pair + ".gene_level.txt"), "".join(gl))
        _w(os.path.join(fit_dir, pair + ".ccf.maf"), MAF_HEADER)
        _w(os.path.join(fit_dir, pair + ".nonsignedout.ccf.maf"), MAF_HEADER)


def write_manifest(path, pair, fake_dir, rows, comment_line=True):
    """rows: list of (fit_name, review_status, reviewed_by, facets_qc)."""
    out = [MANIFEST_COMMENT] if comment_line else []
    out.append(MANIFEST_HEADER)
    for fit_name, status, reviewer, qc in rows:
        out.append("\t".join([pair, fake_dir, status, fit_name, "NA", reviewer, "NA", str(qc).upper(),
                              "NA", "NA", "NA", "1.0", "2.0.8"]) + "\n")
    _w(path, "".join(out))


def write_facets_qc(path, pair, fake_dir, rows):
    """rows: list of (fit_name, is_best_fit, facets_qc)."""
    out = [FACETS_QC_HEADER]
    for fit_name, best, qc in rows:
        out.append("\t".join([pair, fake_dir, fit_name, "0.62", "2.1", "-0.12", "FALSE", "0.21", "0.13",
                              str(best).upper(), "2.0.8", "1.0", str(qc).upper()]) + "\n")
    _w(path, "".join(out))


def write_sample_dir(class_dir, pair, fits, comment_line=True, fake_prefix="/nonexistent/repo", fit_kwargs=None):
    """Write a complete standard-shaped sample (or 2n class) directory.

    fits: list of dicts {fit_name, status, reviewed_by, facets_qc, ultra(bool), with_rdata(bool)}.
    A fit_name of "Not selected" writes a manifest row only.
    """
    fit_kwargs = fit_kwargs or {}
    fake_dir = fake_prefix + "/" + os.path.basename(os.path.dirname(class_dir.rstrip("/"))) + "/" + \
        "/".join(class_dir.rstrip("/").split("/")[-1:]) + "/"
    manifest_rows, qc_rows = [], []
    for f in fits:
        name = f["fit_name"]
        manifest_rows.append((name, f.get("status", "not_reviewed"), f.get("reviewed_by", "NA"), f.get("facets_qc", True)))
        if name == "Not selected":
            continue
        qc_rows.append((name, f.get("status") in ("reviewed_best_fit", "auto_qc_best_fit"), f.get("facets_qc", True)))
        if f.get("ultra"):
            write_fit(os.path.join(class_dir, name), pair, modes=("hisens",), with_qc_gene=False,
                      with_rdata=f.get("with_rdata", True), **fit_kwargs)
        else:
            write_fit(os.path.join(class_dir, name), pair, with_rdata=f.get("with_rdata", True), **fit_kwargs)
    write_manifest(os.path.join(class_dir, "facets_review.manifest"), pair, fake_dir, manifest_rows, comment_line)
    write_facets_qc(os.path.join(class_dir, "facets_qc.txt"), pair, fake_dir, qc_rows)
    _w(os.path.join(class_dir, pair + ".maf"), MAF_HEADER)
    _w(os.path.join(class_dir, pair + ".nonsignedout.maf"), MAF_HEADER)


def _pair(n, t="T01", nn="N01", panel="IM6"):
    tumor = "P-%07d-%s-%s" % (n, t, panel)
    normal = "P-%07d-%s-%s" % (n, nn, panel)
    return tumor, tumor + "_" + normal


def build(root, with_2n=True):
    """Create the fixture repository under ``root`` and return expectations."""
    root = os.path.join(root, "all")
    os.makedirs(root, exist_ok=True)
    info = {"repo": root + "/", "standard": {}, "twon": {}, "clinical_file": None}

    def sdir(tumor, pair):
        return os.path.join(root, tumor[0:7], pair)

    # (a) reviewed best fit (alt) + default
    tumor, pair = _pair(1)
    write_sample_dir(sdir(tumor, pair), pair, [
        {"fit_name": "default", "status": "not_reviewed"},
        {"fit_name": "alt_dipLogR_-0.1", "status": "reviewed_best_fit", "reviewed_by": "alice"},
    ])
    info["standard"]["reviewed_best"] = (tumor, pair)

    # (b) autoQC only: default = auto_qc_pass, alt = auto_qc_best_fit
    tumor, pair = _pair(2)
    write_sample_dir(sdir(tumor, pair), pair, [
        {"fit_name": "default", "status": "auto_qc_pass", "reviewed_by": "auto-qc"},
        {"fit_name": "alt_dipLogR_0.2", "status": "auto_qc_best_fit", "reviewed_by": "auto-qc"},
    ])
    info["standard"]["autoqc_only"] = (tumor, pair)

    # (c) default only, plus a reviewed_no_fit "Not selected" row
    tumor, pair = _pair(3)
    write_sample_dir(sdir(tumor, pair), pair, [
        {"fit_name": "default", "status": "not_reviewed"},
        {"fit_name": "Not selected", "status": "reviewed_no_fit", "reviewed_by": "bob"},
    ])
    info["standard"]["default_only"] = (tumor, pair)

    # (d) directory exists but no manifest
    tumor, pair = _pair(4)
    os.makedirs(sdir(tumor, pair), exist_ok=True)
    info["standard"]["no_manifest"] = (tumor, pair)

    # (e) manifest WITHOUT the comment line; acceptable fit; no Rdata files
    tumor, pair = _pair(5)
    write_sample_dir(sdir(tumor, pair), pair, [
        {"fit_name": "default", "status": "reviewed_acceptable_fit", "reviewed_by": "carol", "with_rdata": False},
    ], comment_line=False)
    info["standard"]["no_comment_acceptable"] = (tumor, pair)

    # (f) two normals: N01 default not_reviewed; N02 default reviewed_best_fit
    tumor, pair1 = _pair(6)
    _, pair2 = _pair(6, nn="N02")
    write_sample_dir(sdir(tumor, pair1), pair1, [{"fit_name": "default", "status": "not_reviewed"}])
    write_sample_dir(sdir(tumor, pair2), pair2, [{"fit_name": "default", "status": "reviewed_best_fit", "reviewed_by": "dan"}])
    info["standard"]["multi_normal"] = (tumor, pair1, pair2)

    # (i) in the clinical file but no directory at all
    tumor_missing, _ = _pair(9)
    info["standard"]["no_dir"] = (tumor_missing, None)

    if with_2n:
        # (g) 2n pair: clinical autoqc best on default; research has default autoqc best, alt, ultras, Not selected
        tumor, pair = _pair(7)
        base = sdir(tumor, pair)
        write_sample_dir(os.path.join(base, "clinical"), pair, [
            {"fit_name": "default", "status": "auto_qc_best_fit", "reviewed_by": "auto-qc"},
            {"fit_name": "alt_dipLogR_-0.1", "status": "not_reviewed"},
            {"fit_name": "Not selected", "status": "not_reviewed"},
        ])
        write_sample_dir(os.path.join(base, "research"), pair, [
            {"fit_name": "default", "status": "auto_qc_best_fit", "reviewed_by": "auto-qc"},
            {"fit_name": "alt_dipLogR_-0.1", "status": "not_reviewed"},
            {"fit_name": "default/ultra", "status": "not_reviewed", "ultra": True},
            {"fit_name": "alt_dipLogR_-0.1/ultra", "status": "auto_qc_pass", "reviewed_by": "auto-qc", "ultra": True},
            {"fit_name": "Not selected", "status": "not_reviewed"},
        ])
        _w(os.path.join(base, "countsMerged____" + pair + ".dat.gz"), "")
        info["twon"]["full"] = (tumor, pair)

        # (h) 2n pair where the top autoqc candidate in research is an ULTRA row
        tumor, pair = _pair(8)
        base = sdir(tumor, pair)
        write_sample_dir(os.path.join(base, "clinical"), pair, [
            {"fit_name": "default", "status": "auto_qc_no_fit", "reviewed_by": "auto-qc"},
            {"fit_name": "Not selected", "status": "auto_qc_no_fit", "reviewed_by": "auto-qc"},
        ])
        write_sample_dir(os.path.join(base, "research"), pair, [
            {"fit_name": "default", "status": "not_reviewed"},
            {"fit_name": "alt_dipLogR_0.3/ultra", "status": "auto_qc_pass", "reviewed_by": "auto-qc", "ultra": True},
        ])
        info["twon"]["ultra_top"] = (tumor, pair)

    # clinical sample file covering every tumor id above (17-char ids), incl. the dir-less one
    tumors = [v[0] for v in info["standard"].values()] + [v[0] for v in info["twon"].values()]
    rows = ["SAMPLE_ID\tPATIENT_ID\tCANCER_TYPE\tCANCER_TYPE_DETAILED\tTUMOR_PURITY\tONCOTREE_CODE\tCVR_TMB_SCORE\tMSI_SCORE\n"]
    types = [("Breast Cancer", "Invasive Ductal Carcinoma", "IDC"), ("Lung Cancer", "Lung Adenocarcinoma", "LUAD")]
    for i, t in enumerate(sorted(set(tumors))):
        ct, ctd, onc = types[i % 2]
        purity = "NA" if i == 2 else str(20 + 10 * i)
        rows.append("\t".join([t, t[0:9], ct, ctd, purity, onc, str(2.5 + i), str(0.5 * i)]) + "\n")
    clin = os.path.join(os.path.dirname(root), "data_clinical_sample.oncokb.txt")
    _w(clin, "".join(rows))
    info["clinical_file"] = clin
    return info


if __name__ == "__main__":
    import sys
    import json
    target = sys.argv[1] if len(sys.argv) > 1 else "fixture_repo"
    print(json.dumps(build(target), indent=2))
